"""Write results/r2/ERROR-ANALYSIS.md: every BOMwitness miss, false positive and clean-image false alarm on the held-out set.

Usage: error_analysis.py [results-dir]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
res = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "results/r2"
s = json.loads((res / "summary.json").read_text())
L = ["# Error analysis (generated by bench/error_analysis.py)", ""]
for split, title in (("heldout", "Held-out images"), ("tuning", "Tuning images")):
    sp = s["splits"][split]
    e = sp["errors"]
    L += [f"## {title}", "", f"Misses: {len(e['misses'])} distinct cases (the honest and stripped rows repeat the colluding row for BOMwitness and are not listed again). "
          f"Case-level false positives: {len(e['false_positives'])}.", "",
          "| Class | Image | Target component | Verdict given | Why |", "|---|---|---|---|---|"]
    for m in sorted(e["misses"], key=lambda m: (m["kind"], m["image"], m["target"])):
        why = m["reason"] or ("the implanted file was flagged as unaccounted executable code; the package was not named"
                              if m["flagged_undeclared_code"] else "no finding")
        if m["other_findings"]:
            why += f" Other findings: {m['other_findings']}."
        L.append(f"| {m['kind']} | {m['image']} | {m['target']} | {m['verdict'] or 'not a declared component'} | {why} |")
    L += ["", "### False alarms on unmodified images with a correct BOM", "", "| Image | Finding | Component |", "|---|---|---|"]
    n = 0
    for iid, im in sp["clean"]["images"].items():
        for cls, comp in im["bw_clean_findings"]:
            L.append(f"| {iid} | {cls} | {comp} |")
            n += 1
    if not n:
        L.append("| none | | |")
    L += ["", "### Components that could not be verified on clean images", "", "| Reason | Count |", "|---|---|"]
    reasons = {}
    for im in sp["clean"]["images"].values():
        for r, k in im["unverifiable_reasons"].items():
            reasons[r] = reasons.get(r, 0) + k
    L += [f"| {r} | {k} |" for r, k in sorted(reasons.items(), key=lambda kv: -kv[1])] + [""]
cb = []
for p in sorted((res / "cbom").glob("*.json")):
    r = json.loads(p.read_text())
    for c in r["cases"]:
        if c["fn"] or c["fp"]:
            cb.append((p.stem, c["kind"], c["labels"], c["extra"]))
L += ["## CBOM and cross-BOM cases with a missing or extra finding", "", "| Image | Class | Expected | Extra |", "|---|---|---|---|"]
L += [f"| {i} | {k} | {l} | {x} |" for i, k, l, x in cb] or ["| none | | | |"]
(res / "ERROR-ANALYSIS.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
