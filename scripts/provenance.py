"""Write docs/PROVENANCE.md from this repository's git history.

The repository is published with its development history, so the freeze commit and its tag can be inspected
directly. This file is a convenience: it lists the commits and the git blob ids of the rule files at the
freeze and now, so a reader can see at a glance which rule files changed after the freeze.
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FREEZE = "rules-frozen-r2a"
RULE_FILES = ["bomwitness/verify.py", "bomwitness/reference.py", "bomwitness/crypto.py", "bomwitness/usign.py", "bomwitness/elfinfo.py",
              "bomwitness/bomio.py", "bomwitness/devicedb.py", "bomwitness/aibom.py", "bomwitness/unpack.py", "bench/run_cases.py",
              "bench/baselines.py", "bench/summarize.py"]


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def blob(rev: str, path: str) -> str:
    r = subprocess.run(["git", "rev-parse", f"{rev}:{path}"], cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else "absent"


freeze = git("rev-parse", FREEZE + "^{commit}")
head = git("rev-parse", "HEAD")
L = ["# Provenance of this repository", "",
     "This repository is published with its development history. No commit was rewritten for publication, so the",
     "commit ids that the documentation and the paper quote (the rule freeze `" + freeze[:7] + "`, tag `" + FREEZE + "`, and the",
     "frozen full run in `results/r2/RUN.json`) can be looked up here, and",
     "`git diff " + FREEZE + " -- bomwitness bench` shows every later change to the rule and benchmark files.", "",
     "What the history can and cannot show: commit times are local git timestamps written on the author's machine.",
     "They give the order in which rules and results entered the repository. They are not an independent timestamp,",
     "and nothing here proves when a result was first looked at.", "",
     "Every commit is authored and committed as Andrew Winton with a GitHub no-reply address. The work was done with",
     "AI coding agents under the author's direction; commit trailers say so.", "",
     "Generated by `scripts/provenance.py`. Times are UTC.", "",
     "## History", "", "| Commit | Time (UTC) | Subject |", "|---|---|---|"]
for line in git("log", "--reverse", "--format=%h|%cd|%s", "--date=format-local:%Y-%m-%d %H:%M").splitlines():
    h, d, s = line.split("|", 2)
    mark = " (rule freeze, tag `" + FREEZE + "`)" if freeze.startswith(h) else ""
    L.append(f"| `{h}` | {d} | {s}{mark} |")
L += ["", "The commit that refreshes this file is not listed in it; `git log` is the authority.", "",
      "## Rule and benchmark files: at the freeze and now", "",
      "Git blob ids (SHA-1 of the file contents as git stores them). `git hash-object <file>` in this repository",
      "reproduces the right-hand column; `git rev-parse " + FREEZE + ":<file>` the middle one.", "", "| File | At the freeze | At the time of writing | Changed |", "|---|---|---|---|"]
for f in RULE_FILES:
    a, b = blob(freeze, f), blob("HEAD", f)
    L.append(f"| `{f}` | `{a[:12]}` | `{b[:12]}` | {'no' if a == b else 'yes'} |")
changed = [f for f in RULE_FILES if blob(freeze, f) != blob("HEAD", f)]
L += ["", "Changed after the freeze: " + (", ".join(f"`{f}`" for f in changed) or "none") + ". What changed and why is listed in",
      "`docs/EVALUATION.md` under \"Changes after the freeze\", with the rerun that shows the scores did not move",
      "(`results/r2/postfreeze-check/COMPARISON.json`).", ""]
(ROOT / "docs/PROVENANCE.md").write_text("\n".join(L))
print("\n".join(L))
