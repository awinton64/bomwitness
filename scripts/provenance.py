"""Write docs/PROVENANCE.md from the development repository's git history.

The public repository is a single-commit export, so the commit ids quoted in the documentation (the rule
freeze, the frozen full run) cannot be looked up there. This script records, from the development history,
the commit list and the git blob ids of the rule files at the freeze and at the exported commit, so a reader
can see exactly which rule files changed after the freeze. Run it in the development repository before an export.
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FREEZE = "rules-frozen-r2a"
RULE_FILES = ["bomwitness/verify.py", "bomwitness/reference.py", "bomwitness/crypto.py", "bomwitness/usign.py", "bomwitness/elfinfo.py",
              "bomwitness/bomio.py", "bomwitness/devicedb.py", "bomwitness/aibom.py", "bomwitness/unpack.py", "bench/run_cases.py",
              "bench/baselines.py", "bench/summarize.py"]


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def blob(rev: str, path: str) -> str:
    r = subprocess.run(["git", "rev-parse", f"{rev}:{path}"], cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else "absent"


freeze = git("rev-parse", FREEZE + "^{commit}")
head = git("rev-parse", "HEAD")
L = ["# Provenance of this repository", "",
     "This public repository is a single-commit export of a private development repository. The commit ids that the",
     "documentation and the paper quote (the rule freeze `" + freeze[:7] + "`, the frozen full run in `results/r2/RUN.json`)",
     "belong to that development history and cannot be looked up here. Nothing in this repository lets a reader verify",
     "the order of events independently; this file states it as precisely as the development history allows.", "",
     "Generated by `scripts/provenance.py` in the development repository. Times are UTC.", "",
     "## Development history", "", "| Commit | Time (UTC) | Subject |", "|---|---|---|"]
for line in git("log", "--reverse", "--format=%h|%cd|%s", "--date=format-local:%Y-%m-%d %H:%M").splitlines():
    h, d, s = line.split("|", 2)
    mark = " (rule freeze, tag `" + FREEZE + "`)" if freeze.startswith(h) else ""
    L.append(f"| `{h}` | {d} | {s}{mark} |")
L += ["", "Later commits (this file, release preparation) are not listed; the export is made from the commit after them.", "",
      "## Rule and benchmark files: at the freeze and now", "",
      "Git blob ids (SHA-1 of the file contents as git stores them). `git hash-object <file>` in this repository",
      "reproduces the right-hand column.", "", "| File | At the freeze | At the time of writing | Changed |", "|---|---|---|---|"]
for f in RULE_FILES:
    a, b = blob(freeze, f), blob("HEAD", f)
    L.append(f"| `{f}` | `{a[:12]}` | `{b[:12]}` | {'no' if a == b else 'yes'} |")
changed = [f for f in RULE_FILES if blob(freeze, f) != blob("HEAD", f)]
L += ["", "Changed after the freeze: " + (", ".join(f"`{f}`" for f in changed) or "none") + ". What changed and why is listed in",
      "`docs/EVALUATION.md` under \"Changes after the freeze\", with the rerun that shows the scores did not move",
      "(`results/r2/postfreeze-check/COMPARISON.json`).", ""]
(ROOT / "docs/PROVENANCE.md").write_text("\n".join(L))
print("\n".join(L))
